function detectLanguage(text, selected) {
  if (selected !== "auto") return selected;
  if (/[\u0C00-\u0C7F]/.test(text)) return "te";
  if (/[\u0900-\u097F]/.test(text)) return "hi";
  return "en";
}

function languageName(code) {
  return ({ en: "English", te: "Telugu (తెలుగు)", hi: "Hindi (हिन्दी)" })[code] || "Unknown";
}

function classify(text) {
  const normalized = text.toLowerCase();
  for (const rule of rules.slice(0, -1)) {
    if (rule.keywords.some(keyword => normalized.includes(keyword.toLowerCase()))) return rule;
  }
  return rules[rules.length - 1];
}

function renderResult(text) {
  const language = detectLanguage(text, languageSelect.value);
  const route = classify(text);

  document.getElementById("result-title").textContent = "Suggested complaint route";
  document.getElementById("result-language").textContent = languageName(language);
  document.getElementById("result-category").textContent = route.category;
  document.getElementById("result-department").textContent = route.department;
  document.getElementById("result-action").textContent = route.action;
  document.getElementById("priority-badge").textContent = `${route.priority} priority`;
  document.getElementById("result-note").textContent =
    "This result is generated by simple keyword matching. It may not understand every phrase or dialect, so please verify the recommendation.";
  result.classList.remove("hidden");
  result.scrollIntoView({ behavior: "smooth", block: "start" });
}

form.addEventListener("submit", event => {
  event.preventDefault();
  const text = complaintInput.value.trim();
  if (!text) {
    complaintInput.focus();
    return;
  }
  renderResult(text);
});

document.querySelectorAll(".example-chip").forEach(button => {
  button.addEventListener("click", () => {
    complaintInput.value = button.dataset.example;
    if (/[\u0C00-\u0C7F]/.test(complaintInput.value)) languageSelect.value = "te";
    else if (/[\u0900-\u097F]/.test(complaintInput.value)) languageSelect.value = "hi";
    else languageSelect.value = "en";
    complaintInput.focus();
  });
});
